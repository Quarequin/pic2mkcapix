void *memset(void *destination, int value, __SIZE_TYPE__ count) {
	uint8_t *bytes = (uint8_t *)destination;
	for (__SIZE_TYPE__ index = 0; index < count; ++index) bytes[index] = (uint8_t)value;
	return destination;
}

